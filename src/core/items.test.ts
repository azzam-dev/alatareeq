describe('أغراض مو في القاموس، ومهام غير الشراء', () => {
  it('الغرض بعد فعل الشراء أو بعد «و»', () => cases([
    ['ابي اشتري بطاقة سوا', ['بطاقة سوا']],
    ['ابي اشتري شي بطاقة سوا', ['بطاقة سوا']],
    ['خبز وبطاقة سوا', ['خبز', 'بطاقة سوا']],
  ]));
  it('فعل المهمة يبقى', () => cases([
    ['ادفع الفاتورة', ['ادفع الفاتورة']],
    ['ابي اعبي لي السيارة', ['اعبي السيارة']],
    ['خليني ادفع الفاتورة', ['ادفع الفاتورة']],
    ['اشتري خبز واعبي السيارة', ['خبز', 'اعبي السيارة']],
    ['اطبع ورق', ['اطبع ورق']],
  ]));
  it('تذكير بدون أغراض واضحة ينحسب غرض واحد', () => {
    expect(reminderItems('أعبي')).toEqual(['أعبي']);
    expect(reminderItems('ضروري')).toEqual(['ضروري']);
    expect(reminderItems('')).toEqual(['تذكير']);
  });
});

describe('عنوان التذكير بالأغراض بس', () => {
  it('بفواصل', () => {
    expect(cleanTitle('خليني اشتري خبز وزبادي وصامولي وعصير ربيع')).toBe('خبز، زبادي، صامولي، عصير ربيع');
    expect(cleanTitle('ابي اشتري حاجة خبز وصامولي')).toBe('خبز، صامولي');
    expect(cleanTitle('خليني اشتري عسل حجم كبير ولبن صغير الله يعافيك')).toBe('عسل حجم كبير، لبن صغير');
    expect(cleanTitle('أشتري دواء')).toBe('دواء');
  });
  it('عناوين انحفظت غلط قبل تتنظّف', () => {
    expect(cleanTitle('خليني، خبز، صامولي، زبادي وعصير ربيع')).toBe('خبز، صامولي، زبادي، عصير ربيع');
    expect(cleanTitle('حاجة، خبز، صامولي')).toBe('خبز، صامولي');
    expect(cleanTitle('‏راح، خبز ولبن')).toBe('خبز، لبن');
  });
  it('المهام غير الشراء، والعنوان بدون أغراض، يبقون مثل ما هم', () => {
    expect(cleanTitle('أعبي السيارة')).toBe('أعبي السيارة');
    expect(cleanTitle('ادفع الفاتورة')).toBe('ادفع الفاتورة');
    expect(cleanTitle('تذكير')).toBe('تذكير');
    expect(cleanTitle('')).toBe('');
  });
  it('التنظيف مرتين نفس مرة وحدة (تنظيف التذاكير المحفوظة)', () => {
    for (const t of [
      'خليني اشتري خبز وزبادي وصامولي وعصير ربيع', 'خليني اشتري عسل حجم كبير ولبن صغير الله يعافيك',
      'اشتري كيلو طماطم وعلبة تونة', 'اشتري ورق عنب وخبز', 'اشتري خبز واعبي السيارة', 'اشتري هدية والدي وخبز',
      'اشتري ماء ١.٥ لتر وخبز', 'اشتري عصير برتقال وزيت زيتون', 'خبز وبطاقة سوا', 'اشتري حليب المراعي قليل الدسم',
    ]) {
      expect(cleanTitle(cleanTitle(t)), t).toBe(cleanTitle(t));
    }
  });
  it('تركيب العنوان', () => {
    expect(joinItems(['زبادي'])).toBe('زبادي');
    expect(joinItems(['خبز', 'صامولي', 'زبادي'])).toBe('خبز، صامولي، زبادي');
    expect(joinItems([])).toBe('');
  });
});

