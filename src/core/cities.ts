export function cityOf(p: { lat: number; lon: number }): string | undefined {
  let best: { name: string; d: number } | undefined;
  for (const [name, lat, lon, km] of CITIES) {
    const d = distanceM(p, { lat, lon });
    if (d <= km * 1000 && (!best || d < best.d)) best = { name, d };
  }
  return best?.name;
}
